# Generates build_identity.h: git SHA (+ "-dirty"), branch and canary number.
# Run as an xrCore pre-build step. The output is gitignored.
#
#   CANARY_NUMBER    canary number set by CI; "local" when unset
#   XR_BUILD_BRANCH  branch name to use when HEAD is detached (CI checks out a SHA)

param(
    [Parameter(Mandatory = $true)][string]$OutFile
)

$ErrorActionPreference = 'Stop'
$repo = $PSScriptRoot

function Invoke-Git([string[]]$GitArgs)
{
    try
    {
        $out = & git -C $repo @GitArgs 2>$null
        if ($LASTEXITCODE -ne 0) { return $null }
        return $out
    }
    catch
    {
        return $null
    }
}

$sha = Invoke-Git @('rev-parse', '--short=7', 'HEAD')
if (-not $sha) { $sha = 'unknown' }
else
{
    $status = Invoke-Git @('status', '--porcelain', '--untracked-files=no')
    if ($status) { $sha = "$sha-dirty" }
}

$branch = Invoke-Git @('rev-parse', '--abbrev-ref', 'HEAD')
if (-not $branch -or $branch -eq 'HEAD')
{
    if ($env:XR_BUILD_BRANCH) { $branch = $env:XR_BUILD_BRANCH }
    elseif ($branch -eq 'HEAD') { $branch = 'detached' }
    else { $branch = 'unknown' }
}

if ($env:CANARY_NUMBER) { $canary = "canary-$($env:CANARY_NUMBER)" }
else { $canary = 'local' }

function Quote([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

$content = @"
// Generated by build_identity.ps1. Do not edit or commit.
#pragma once
#define XR_BUILD_SHA $(Quote $sha)
#define XR_BUILD_BRANCH $(Quote $branch)
#define XR_BUILD_CANARY $(Quote $canary)
"@

# Only touch the file when it changes, so unchanged builds don't recompile.
$existing = $null
if (Test-Path $OutFile) { $existing = [System.IO.File]::ReadAllText($OutFile) }
if ($existing -ne $content)
{
    [System.IO.File]::WriteAllText($OutFile, $content, [System.Text.Encoding]::ASCII)
    Write-Host "build_identity: $canary ($sha) $branch"
}
